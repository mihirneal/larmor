//! Volume operations for MRI preprocessing, matching nibabel, scipy.ndimage and numpy bit for bit
//! where that is achievable.
//!
//! The pieces mirror the Python functions nanobrain's preprocessing calls:
//!
//! | Here | Python |
//! |---|---|
//! | [`Nifti::read`], [`Nifti::write`] | `nibabel.load`, `nibabel.save` |
//! | [`Nifti::affine`], [`Nifti::zooms`], [`Nifti::fdata_f32`] | `img.affine`, `header.get_zooms()`, `img.get_fdata(np.float32)` |
//! | [`Nifti::dataobj`] | `np.asanyarray(img.dataobj)` |
//! | [`Nifti::resample_to_f32`] | `resample_from_to(img, (shape, affine), order).get_fdata(np.float32)` |
//! | [`Nifti::fdata_f32_oriented`] | `apply_orientation(img.get_fdata(np.float32), ornt)` |
//! | [`io_orientation`], [`Volume::as_closest_canonical`] | `nibabel.orientations.io_orientation`, `nibabel.as_closest_canonical` |
//! | [`affine_transform`], [`resample_from_to`], [`vox2out_vox`] | `scipy.ndimage.affine_transform`, `nibabel.processing.resample_from_to`, `nibabel.spaces.vox2out_vox` |
//! | [`gaussian_filter`] | `scipy.ndimage.gaussian_filter` |
//! | [`label`], [`largest_component`], [`binary_fill_holes`] | `scipy.ndimage.label`, nanobrain's `largest_component`, `scipy.ndimage.binary_fill_holes` |
//! | [`mean_f32`], [`quantiles_linear`] | `ndarray.mean()` (float32), `np.quantile` |
//!
//! Arrays are [`ndarray`] arrays indexed `[x, y, z]`, like the numpy arrays nibabel returns.
//!
//! Bit-exactness depends on rounding details that are easy to miss, and each is called out where
//! it happens: numpy's pairwise float32 sums, float32-versus-float64 promotion of scalars, the
//! fused multiply-adds in scipy's C loops and in Accelerate's BLAS/LAPACK (numpy and scipy on this
//! Mac), and scipy's write-back rounding for integer images. `tests/reference.rs` checks every op
//! against outputs generated by `tests/data/make_test_data.py`.

